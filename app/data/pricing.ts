/**
 * Типы бруса и расход на 1 м² площади (k = V / S).
 * k посчитан по кубатурам заводского каталога — по моделям того же сечения:
 * база — медиана, min/max — края наблюдаемого коридора.
 * Поэтому расчёт по м² даёт вилку, а не точку.
 */
export interface Timber {
  id: string
  label: string
  short: string
  /** расход м³ на 1 м² площади: минимум, медиана, максимум */
  k: { min: number; base: number; max: number }
  /** на каких моделях каталога построен коридор */
  basis: string
}

